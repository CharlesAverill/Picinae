#!/usr/bin/env python3
"""Generate proofs/intops_proof.v: labs/llabs/imaxabs and htonl/ntohl/htons/ntohs."""
import subprocess
def addr(f):
    lines=open(f'programs/{f}_amd64.v').read().splitlines()
    ent=[l for l in lines if l.startswith('(* 0x')][0][3:13]
    ret=[l for l in lines if l.startswith('(* 0x') and ': RET' in l][0][3:13]
    return hex(int(ent,16)), hex(int(ret,16))
F=[("labs","abs64"),("llabs","abs64"),("imaxabs","abs64"),
   ("htonl","bswap32"),("ntohl","bswap32"),("htons","bswap16"),("ntohs","bswap16")]
HEADER='''(* labs, llabs, imaxabs; htonl, ntohl, htons, ntohs (musl x86_64, C)

   SEMANTICS
   ---------
   labs/llabs/imaxabs (src/stdlib/labs.c etc.) return a>0 ? a : -a for a
   64-bit long; GCC emits NEG + CMOVS.  For LONG_MIN, where the C result is
   undefined, -a wraps back to LONG_MIN, so the result is LONG_MIN.
   htonl/ntohl (src/network/htonl.c) are __bswap_32 (BSWAP); htons/ntohs are
   __bswap_16, compiled to MOV EAX,EDI; ROL AX,8.  The 16-bit functions
   leave EDI's bits 16..31 in EAX: only AX is the uint16_t result (the ABI
   leaves the upper bits of a narrow return value unspecified), and the
   theorems state both the exact RAX and its low 16 bits.

   SPECIFICATION (man 3 labs, man 3 htonl, Linux man-pages 6.9.1)
   --------------------------------------------------------------

     SYNOPSIS
            #include <stdlib.h>
            long labs(long j);   long long llabs(long long j);
            #include <inttypes.h>
            intmax_t imaxabs(intmax_t j);
            #include <arpa/inet.h>
            uint32_t htonl(uint32_t hostlong);   uint16_t htons(uint16_t hostshort);
            uint32_t ntohl(uint32_t netlong);    uint16_t ntohs(uint16_t netshort);

     DESCRIPTION
            The abs() function computes the absolute value of the integer
            argument j.  The labs(), llabs(), and imaxabs() functions compute
            the absolute value of the argument j of the appropriate integer
            type for the function.
            Trying to take the absolute value of the most negative integer
            is not defined.
            The htonl() function converts the unsigned integer hostlong from
            host byte order to network byte order.  The htons() function
            converts the unsigned short integer hostshort from host byte
            order to network byte order.  The ntohl() function converts the
            unsigned integer netlong from network byte order to host byte
            order.  The ntohs() function converts the unsigned short integer
            netshort from network byte order to host byte order.
            On the i386 the host byte order is Least Significant Byte first,
            whereas the network byte order, as used on the Internet, is Most
            Significant Byte first.

   PROVENANCE
   ----------
   Binary:  alpine_musl/x86_64/lib/libc.musl-x86_64.so.1, Alpine musl-1.2.6-r6
            sha256 cc3e02006173e4d7c11c5d37deded8749cfe7786f71a70a5c87fa6f509714647
   Lifter:  Ghidra 12.0 (headless) + pcode2coq (tools/ghidra-lifter) with
            --globalAddressing; see programs/<f>_amd64.v.  Generated by
            tools/gen_misc.py.
   Model:   This specification and proof were written by Claude Opus 5.5
            (claude-opus-5-5), an AI model by Anthropic, and machine-checked
            by Rocq 9.1.

   INPUT/OUTPUT SPECIFICATION (System V AMD64 ABI)
   -----------------------------------------------
   Input:   RDI = the argument.
   Output:  At the RET: labs/llabs/imaxabs: RAX = |j| mod 2^64 for the signed
            64-bit reading j of RDI (abs64_value: exactly |j| unless
            j = LONG_MIN).  htonl/ntohl: RAX = bswap32 (EDI), the byte reversal
            of the low 32 bits.  htons/ntohs: RAX mod 2^16 = bswap16 (DI).
            RSP and RBX, RBP, R12-R15 are unchanged; no memory is written.
 *)

'''
out=[HEADER,'''Require Import Picinae_amd64.
'''+''.join(f"Require Import CoqEtTu.programs.{n}_amd64.\n" for n,_ in F)+'''Import X64Notations.
From Stdlib Require Import NArith ZArith Lia List.
Import ListNotations.
Require Import CoqEtTu.lib.x64_common CoqEtTu.lib.x64_abi.
Open Scope N.

Definition abs64 (x:N) := ofZ 64 (Z.abs (toZ 64 x)).
Definition bswap32 (x:N) :=
  xbits x 0 8 << 24 .| xbits x 8 16 << 16 .| xbits x 16 24 << 8 .| xbits x 24 32.
Definition bswap16 (x:N) := xbits x 0 8 << 8 .| xbits x 8 16.

Lemma abs64_math:
  forall n, let j := toZ 64 n in
  (slt 64 (msub 64 0 n) 0 = true -> n mod 2^64 = ofZ 64 (Z.abs j)) /\\
  (slt 64 (msub 64 0 n) 0 = false -> msub 64 0 n = ofZ 64 (Z.abs j)).
Proof.
  intros n j.
  assert (V: msub 64 0 n = ofZ 64 (- j)) by (rewrite msub_sbop; reflexivity).
  assert (TV: toZ 64 (msub 64 0 n) = canonicalZ 64 (- j)) by (rewrite toZ_msub; reflexivity).
  assert (N: n mod 2^64 = ofZ 64 j) by (symmetry; apply ofZ_toZ_bitcast; reflexivity).
  unfold slt. rewrite TV. change (toZ 64 0) with 0%Z.
  pose proof (toZ64_range n) as R. fold j in R.
  destruct (Z.lt_trichotomy j 0) as [NEG|[Z0|POS]].
    destruct (Z.eq_dec j (-2^63)) as [MIN|NMIN].
      rewrite MIN. split; intro BC. rewrite N, MIN. reflexivity. discriminate BC.
      rewrite (canonicalZ_id 64) by (unfold signed_range; simpl; lia).
      replace (- j <? 0)%Z with false by (symmetry; apply Z.ltb_ge; lia).
      split; intro BC. discriminate BC. rewrite V, Z.abs_neq by lia. reflexivity.
    rewrite Z0. split; intro BC. discriminate BC. rewrite V, Z0. reflexivity.
    rewrite (canonicalZ_id 64) by (unfold signed_range; simpl; lia).
    replace (- j <? 0)%Z with true by (symmetry; apply Z.ltb_lt; lia).
    split; intro BC. rewrite N, Z.abs_eq by lia. reflexivity. discriminate BC.
Qed.

(* For every j other than LONG_MIN the result read as signed is exactly |j|. *)
Theorem abs64_value:
  forall j, (-2^63 < j < 2^63)%Z -> toZ 64 (ofZ 64 (Z.abs j)) = Z.abs j.
Proof.
  intros j R. rewrite toZ_ofZ_canonicalZ by reflexivity.
  apply (canonicalZ_id 64). reflexivity. unfold signed_range. simpl. lia.
Qed.
''']
for n,kind in F:
    ent,ret=addr(n)
    if kind=="abs64": post="s R_RAX = abs64 x"
    elif kind=="bswap32": post="s R_RAX = bswap32 x"
    else: post="s R_RAX mod 2^16 = bswap16 x"
    out.append(f'''
(* ---- {n} ---- *)
Theorem {n}_nwc: forall s2 s1, {n}_amd64 s1 = {n}_amd64 s2.
Proof. reflexivity. Qed.

Theorem {n}_welltyped: welltyped_prog x64typctx {n}_amd64.
Proof. exact {n}_amd64.welltyped. Qed.

Theorem {n}_preserves_memory:
  forall_endstates {n}_amd64 (fun _ s _ s' => s V_MEM64 = s' V_MEM64).
Proof. apply noassign_prog_same. prove_noassign. Qed.

Definition {n}_exit (t:trace) :=
  match t with (Addr a,_)::_ => match a with {ret} => true | _ => false end | _ => false end.

Definition {n}_invs (s0:store) (x:N) (t:trace) :=
  match t with (Addr a,s)::_ => match a with
  | {ent} => Some (s R_RDI = x /\\ s R_RSP = s0 R_RSP /\\ callee_saved_eq s0 s)
  | {ret} => Some ({post} /\\ s R_RSP = s0 R_RSP /\\ callee_saved_eq s0 s)
  | _ => None end | _ => None end.

Theorem {n}_correct:
  forall prog s t s' x' x
         (SUB: {n}_amd64 ⊆2 prog)
         (ENTRY: startof t (x',s') = (Addr {ent}, s))
         (MDL: models x64typctx s) (X: s R_RDI = x),
  satisfies_all prog ({n}_invs s x) {n}_exit ((x',s')::t).
Proof.
  intros prog s0 t s' x' x SUB ENTRY MDL X.
  eapply satisfies_all_pmono with (p1:={n}_amd64); [exact SUB| |].
    intros a s1 t1 EXIT NOCODE. unfold {n}_invs.
    repeat first
    [ reflexivity | discriminate EXIT | discriminate NOCODE
    | match goal with |- context [match ?n with _ => _ end] => destruct n end ].
  intros [x1 s1] t1 START. rewrite ENTRY in START.
  clear - s0 x MDL X START.
  rename t1 into t. rename s1 into s'. rename x1 into x'. rename START into ENTRY.
  apply prove_invs.
  simpl. rewrite ENTRY. x64_step. conj_tac. apply callee_saved_eq_refl.
  intros.
  erewrite startof_prefix in ENTRY; try eassumption.
  eapply models_at_invariant; try eassumption. apply {n}_welltyped. intro MDL1.
  assert (XB: x < 2^64) by (destruct_inv 64 PRE; destruct PRE as [RDI _]; rewrite <- RDI;
                            apply (MDL1 R_RDI 64); reflexivity).
  clear - PRE MDL1 XB. rename t1 into t.
  destruct_inv 64 PRE.
  destruct PRE as [RDI [RSP CS]].
  repeat x64_step.
  all: split; [|conj_tac].
''')
    if kind=="abs64":
        out.append(f'''  all: unfold abs64.
  all: match goal with BC: slt 64 _ 0 = _ |- _ => idtac | _ => idtac end.
  all: first [ apply (proj1 (abs64_math x)); assumption
             | apply (proj2 (abs64_math x)); assumption
             | rewrite <- (N.mod_small x (2^64)) at 1 by exact XB; apply (proj1 (abs64_math x)); assumption ].
Qed.
''')
    elif kind=="bswap32":
        out.append('''  all: unfold bswap32; bitblast_upto 32.
Qed.
''')
    else:
        out.append('''  all: unfold bswap16; bitblast_upto 16.
Qed.
''')
open('proofs/intops_proof.v','w').write(''.join(out))
