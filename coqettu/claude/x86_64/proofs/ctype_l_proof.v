(* ---- isalnum_l ---- *)
Definition isalnum_l_program : program := updateall2 isalnum_l_amd64 isalnum_amd64.

Lemma isalnum_l_program_welltyped: welltyped_prog x64typctx isalnum_l_program.
Proof.
  intros s a. unfold isalnum_l_program, updateall2, updateall.
  destruct (isalnum_amd64 s a) as [[sz q]|] eqn:SL.
    pose proof (isalnum_welltyped s a) as WT. rewrite SL in WT. exact WT.
    apply isalnum_l_amd64.welltyped.
Qed.

Definition isalnum_l_invs (s0:store) (c:N) (t:trace) :=
  match t with (Addr a,s)::_ => match a with
  | 0x1415a9 => Some (s R_RDI = c /\ s V_MEM64 = s0 V_MEM64 /\ s R_RSP = s0 R_RSP /\ callee_saved_eq s0 s)
  | 0x1415a8 => isalnum_invs s0 c t
  | _ => None end | _ => None end.

Theorem isalnum_l_correct:
  forall prog s t s' x' c
         (SUB: isalnum_l_amd64 ⊆2 prog) (SUBF: isalnum_amd64 ⊆2 prog)
         (ENTRY: startof t (x',s') = (Addr 0x1415a9, s))
         (MDL: models x64typctx s) (C: s R_RDI = c),
  satisfies_all prog (isalnum_l_invs s c) isalnum_exit ((x',s')::t).
Proof.
  intros prog s0 t s' x' c SUB SUBF ENTRY MDL C.
  eapply satisfies_all_pmono with (p1:=isalnum_l_program).
    unfold isalnum_l_program. apply updateall2_lub; assumption.
    intros a s1 t1 EXIT NOCODE. unfold isalnum_l_invs.
    unfold isalnum_l_program, updateall2, updateall in NOCODE.
    repeat first
    [ reflexivity | discriminate EXIT | discriminate NOCODE
    | match goal with |- context [match ?n with _ => _ end] => destruct n end ].
  intros [x1 s1] t1 START. rewrite ENTRY in START.
  clear - s0 c MDL C START.
  rename t1 into t. rename s1 into s'. rename x1 into x'. rename START into ENTRY.
  apply prove_invs.
  simpl. rewrite ENTRY. x64_step. conj_tac. apply callee_saved_eq_refl.
  intros.
  erewrite startof_prefix in ENTRY; try eassumption.
  eapply models_at_invariant; try eassumption. apply isalnum_l_program_welltyped. intro MDL1.
  clear - PRE MDL1. rename t1 into t.
  destruct_inv 64 PRE.
  destruct PRE as [RDI [MEM [RSP CS]]].
  x64_step.
  match goal with |- nextinv _ _ _ _ ((Addr _, ?S)::_) => set (s2 := S) end.
  apply (models_after_steps isalnum_l_program _ _ _ _ s2 nil _ s1 t MDL1 isalnum_l_program_welltyped).
  intro MDL2.
  assert (C02: callee_saved_eq s0 s2) by
    (destruct CS as (B0 & B1 & B2 & B3 & B4 & B5); unfold s2; repeat split; reg; assumption).
  assert (S2M: s2 V_MEM64 = s0 V_MEM64) by (unfold s2; reg; exact MEM).
  assert (S2R: s2 R_RSP = s0 R_RSP) by (unfold s2; reg; exact RSP).
  eapply (tail_leaf_ni isalnum_l_program isalnum_amd64 _ _ (isalnum_invs s2 c) isalnum_exit).
  - apply subset_updateall2.
  - intros a s t' EXIT NOCODE. unfold isalnum_invs.
    repeat first
    [ reflexivity | discriminate EXIT | discriminate NOCODE
    | match goal with |- context [match ?n with _ => _ end] => destruct n end ].
  - intros t' [x' s'] START. apply isalnum_correct; first
      [ apply pf2sub_refl | assumption | reflexivity | (unfold s2; reg; assumption) ].
  - intros a s t' NC X2. unfold isalnum_l_invs, isalnum_exit in *.
    repeat first
    [ split | reflexivity | (exfalso; apply NC; reflexivity) | discriminate X2
    | match goal with |- context [match ?n with _ => _ end] => destruct n end ].
  - intros a s t' X2. unfold isalnum_exit, isalnum_l_invs, isalnum_invs in *.
    repeat first
    [ discriminate X2
    | match goal with |- context [match ?n with _ => _ end] => destruct n end ].
    split. reflexivity. unfold post_or_true, true_inv.
    intros [A [B [D E]]]. split. exact A. split. rewrite B. exact S2M.
    split. rewrite D. exact S2R. exact (callee_saved_eq_trans _ _ _ C02 E).
  - intros [[a|i] s] t'; reflexivity.
  - intros [[a|i] s] t'; reflexivity.
  - intros a s t' X. unfold isalnum_exit in X. addr_cases X; discriminate.
  - split; reflexivity.
  - intros. split; reflexivity.
Qed.

