(* isalnum_l ... isxdigit_l, tolower_l, toupper_l, ispunct_l -- the
   locale variants of <ctype.h> (musl x86_64, C), tail calls into the
   plain functions

   SEMANTICS
   ---------
   musl's src/ctype/<f>.c define, e.g.,

       int __isalpha_l(int c, locale_t l) { return isalpha(c); }
       weak_alias(__isalpha_l, isalpha_l);

   Each compiles to a single JMP into the plain function, whose contract
   (ctype_proof.v, ispunct_proof.v) is used through tail_leaf
   (lib/x64_tail.v).  Generated by tools/gen_ctype_l.py.

   SPECIFICATION (man 3 isalpha, man 3 toupper, Linux man-pages 6.9.1,
   paraphrased)
   ------------------------------------------------------------------
     int isalpha_l(int c, locale_t locale);   (likewise the others)
     The _l variants perform the same check or conversion as the plain
     functions, in the given locale instead of the current one.  musl has
     only the C/POSIX classification, so the locale argument is ignored.

   PROVENANCE
   ----------
   Binary:  alpine_musl/x86_64/lib/libc.musl-x86_64.so.1, Alpine musl-1.2.6-r6
            sha256 cc3e02006173e4d7c11c5d37deded8749cfe7786f71a70a5c87fa6f509714647
            (addresses: see each <f>_l_invs; Ghidra image base 0x100000)
   Lifter:  Ghidra 12.0 (headless) + pcode2coq (tools/ghidra-lifter) with
            --globalAddressing; see programs/<f>_l_amd64.v.
   Model:   This specification and proof were written by Claude Opus 5.5
            (claude-opus-5-5), an AI model by Anthropic, and machine-checked
            by Rocq 9.1.

   INPUT/OUTPUT SPECIFICATION (System V AMD64 ABI)
   -----------------------------------------------
   Input:   RDI = c (the int argument; c mod 2^32), RSI = locale (ignored).
            No precondition.
   Output:  At the plain function's RET, which returns to the caller of
            <f>_l: exactly the plain function's postcondition relative to
            <f>_l's entry state (ctype_proof.v / ispunct_proof.v), e.g.
            RAX = N.b2n (isalpha_spec (c mod 2^32)); memory unchanged (for
            ispunct_l: nothing outside the 16 bytes below rsp changes); RSP
            and RBX, RBP, R12-R15 unchanged.
 *)

