(* iswdigit iswxdigit iswcntrl iswblank and their _l variants -- wide
   character classification (musl x86_64, C)

   SEMANTICS
   ---------
   musl's src/ctype/isw<f>.c define

       int iswdigit(wint_t wc)  { return (unsigned)wc-'0' < 10; }
       int iswxdigit(wint_t wc) { return (unsigned)(wc-'0') < 10 || (unsigned)((wc|32)-'a') < 6; }
       int iswcntrl(wint_t wc)  { return (unsigned)wc < 32 || (unsigned)(wc-0x7f) < 33
                                         || (unsigned)(wc-0x2028) < 2 || (unsigned)(wc-0xfff9) < 3; }
       int iswblank(wint_t wc)  { return isblank(wc); }
       int __iswdigit_l(wint_t c, locale_t l) { return iswdigit(c); }   (likewise)

   iswdigit and iswxdigit compile to exactly the instructions of isdigit and
   isxdigit, so their specifications (isdigit_spec, isxdigit_spec of
   ctype_proof.v) and proof scripts are reused (iswcntrl reuses the
   isdigit script with its own range specification); iswblank is a JMP into
   isblank and the _l variants JMP into the plain functions (tail_leaf,
   lib/x64_tail.v; iswblank_l -> iswblank -> isblank is a nested tail call).
   Generated by tools/gen_wctype.py.

   SPECIFICATION (man 3 iswdigit, iswxdigit, iswblank, Linux man-pages
   6.9.1, paraphrased)
   ------------------------------------------------------------------
     int iswdigit(wint_t wc);  int iswxdigit(wint_t wc);  int iswblank(wint_t wc);
     int iswcntrl(wint_t wc);
     iswdigit tests whether wc is a wide character of class "digit" (only
     the ASCII digits 0-9); iswxdigit whether it is a hexadecimal digit
     (0-9, a-f, A-F); iswcntrl whether it is a control character (C0, DEL
     and C1, U+2028/U+2029, U+FFF9..U+FFFB here); iswblank whether it is a blank (space or horizontal
     tab here; musl's iswblank classifies like isblank).  The _l variants
     take an ignored locale.

   PROVENANCE
   ----------
   Binary:  alpine_musl/x86_64/lib/libc.musl-x86_64.so.1, Alpine musl-1.2.6-r6
            sha256 cc3e02006173e4d7c11c5d37deded8749cfe7786f71a70a5c87fa6f509714647
            iswdigit at 0x417a5, iswdigit_l at 0x417b1, iswxdigit at 0x418dc,
            iswxdigit_l at 0x418f8, iswcntrl at 0x41708, iswcntrl_l at 0x4173a,
            iswblank at 0x416fe, iswblank_l at
            0x41703, isblank at 0x415cb (Ghidra image base 0x100000)
   Lifter:  Ghidra 12.0 (headless) + pcode2coq (tools/ghidra-lifter) with
            --globalAddressing; see programs/isw*_amd64.v.
   Model:   This specification and proof were written by Claude Opus 5.5
            (claude-opus-5-5), an AI model by Anthropic, and machine-checked
            by Rocq 9.1.

   INPUT/OUTPUT SPECIFICATION (System V AMD64 ABI)
   -----------------------------------------------
   Input:   RDI = wc (c mod 2^32 is used), RSI = locale (ignored, _l).
            No precondition.
   Output:  At the RET: RAX = N.b2n (isdigit_spec (c mod 2^32)), resp.
            isxdigit_spec, iswcntrl_spec, resp. isblank's postcondition;
            memory unchanged;
            RSP and RBX, RBP, R12-R15 unchanged.
 *)

