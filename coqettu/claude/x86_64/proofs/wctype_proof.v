(* ---- iswdigit (same code as isdigit) ---- *)

Theorem iswdigit_nwc: forall s2 s1, iswdigit_amd64 s1 = iswdigit_amd64 s2.
Proof. reflexivity. Qed.

Theorem iswdigit_welltyped: welltyped_prog x64typctx iswdigit_amd64.
Proof. exact iswdigit_amd64.welltyped. Qed.

Theorem iswdigit_preserves_memory:
  forall_endstates iswdigit_amd64 (fun _ s _ s' => s V_MEM64 = s' V_MEM64).
Proof. apply noassign_prog_same. prove_noassign. Qed.

Definition iswdigit_exit (t:trace) :=
  match t with (Addr a,_)::_ => match a with 0x1417b0 => true | _ => false end | _ => false end.

Definition iswdigit_invs (s0:store) (c:N) (t:trace) :=
  match t with (Addr a,s)::_ => match a with
  | 0x1417a5 => Some (s R_RDI = c /\ s V_MEM64 = s0 V_MEM64 /\ s R_RSP = s0 R_RSP /\ callee_saved_eq s0 s)
  | 0x1417b0 => Some (s R_RAX = N.b2n (isdigit_spec (c mod 2^32)) /\ s V_MEM64 = s0 V_MEM64 /\ s R_RSP = s0 R_RSP /\ callee_saved_eq s0 s)
  | _ => None end | _ => None end.

Theorem iswdigit_correct:
  forall prog s t s' x' c
         (SUB: iswdigit_amd64 ⊆2 prog)
         (ENTRY: startof t (x',s') = (Addr 0x1417a5, s))
         (MDL: models x64typctx s) (C: s R_RDI = c),
  satisfies_all prog (iswdigit_invs s c) iswdigit_exit ((x',s')::t).
Proof.
  intros prog s0 t s' x' c SUB ENTRY MDL C.
  eapply satisfies_all_pmono with (p1:=iswdigit_amd64); [exact SUB| |].
    intros a s1 t1 EXIT NOCODE. unfold iswdigit_invs.
    repeat first
    [ reflexivity | discriminate EXIT | discriminate NOCODE
    | match goal with |- context [match ?n with _ => _ end] => destruct n end ].
  intros [x1 s1] t1 START. rewrite ENTRY in START.
  clear - s0 c MDL C START.
  rename t1 into t. rename s1 into s'. rename x1 into x'. rename START into ENTRY.
  apply prove_invs.
  simpl. rewrite ENTRY. x64_step. conj_tac. apply callee_saved_eq_refl.
  intros.
  erewrite startof_prefix in ENTRY; try eassumption.
  eapply models_at_invariant; try eassumption. apply iswdigit_welltyped. intro MDL1.
  clear - PRE MDL1. rename t1 into t.
  destruct_inv 64 PRE.
  destruct PRE as [RDI [MEM [RSP CS]]].
  repeat x64_step. all: bc_norm.
  all: split; [|conj_tac].
  all: unfold isdigit_spec, inr.
  all: ct_finish.
Qed.

