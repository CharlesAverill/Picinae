(* TIG: closing tactics *)
Local Ltac tig_bc :=
  unfold slt, sle in *;
  repeat match goal with
  | H: Z.ltb _ _ = true |- _ => apply Z.ltb_lt in H
  | H: Z.ltb _ _ = false |- _ => apply Z.ltb_ge in H
  | H: Z.leb _ _ = true |- _ => apply Z.leb_le in H
  | H: Z.leb _ _ = false |- _ => apply Z.leb_gt in H
  | H: Z.geb _ _ = true |- _ => apply Z.geb_le in H
  | H: Z.geb _ _ = false |- _ => rewrite Z.geb_leb in H; apply Z.leb_gt in H
  | H: Z.gtb _ _ = true |- _ => apply Z.gtb_lt in H
  | H: Z.gtb _ _ = false |- _ => rewrite Z.gtb_ltb in H; apply Z.ltb_ge in H
  | H: (_ =? _) = true |- _ => apply N.eqb_eq in H
  | H: (_ =? _) = false |- _ => apply N.eqb_neq in H
  | H: (_ <? _) = true |- _ => apply N.ltb_lt in H
  | H: (_ <? _) = false |- _ => apply N.ltb_ge in H
  | H: (_ <=? _) = true |- _ => apply N.leb_le in H
  | H: (_ <=? _) = false |- _ => apply N.leb_gt in H
  | H: negb _ = true |- _ => apply Bool.negb_true_iff in H
  | H: negb _ = false |- _ => apply Bool.negb_false_iff in H
  end.
Local Ltac tig_split_if c :=
  lazymatch c with true => fail | false => fail
  | negb ?c' => destruct c' eqn:? | _ => destruct c eqn:? end.
Local Ltac tig_ifs :=
  repeat (cbn [negb] in *; match goal with
    | |- context[if ?c then _ else _] => tig_split_if c
    | H: context[if ?c then _ else _] |- _ => tig_split_if c
    end); cbn [negb] in *.
(* turn mod and div into linear constraints *)
Local Ltac tig_pow :=
  repeat match goal with
  | |- context[2 ^ ?n] => let v := eval vm_compute in (2 ^ n) in change (2 ^ n) with v
  | H: context[2 ^ ?n] |- _ => let v := eval vm_compute in (2 ^ n) in change (2 ^ n) with v in H
  end.
Local Ltac tig_arith :=
  tig_bc; unfold msub in *;
  rewrite ?N.shiftl_mul_pow2, ?N.shiftr_div_pow2 in *; tig_pow;
  zify; Z.div_mod_to_equations; Z.quot_rem_to_equations; lia.
(* what psimpl leaves: x xor x (x86 xor eax, eax) and casts of 0 *)
Local Ltac tig_norm :=
  rewrite ?N.lxor_nilpotent, ?N.Div0.mod_0_l in *;
  repeat match goal with
  | |- context[scast ?a ?b 0] =>
      let v := eval vm_compute in (scast a b 0) in change (scast a b 0) with v
  end.
(* Split conjunctions and solve each one. On a path that leaves the loop, the
   iteration i equals the count n. *)
Local Ltac tig_close i n :=
  lazymatch goal with
  | |- _ /\ _ => split; [ tig_close i n | tig_close i n ]
  | |- _ => first [ assumption | reflexivity
                  | tig_norm;
                    (tryif constr_eq i n then idtac else replace i with n in * by tig_arith);
                    hammer; tig_ifs; solve [ lia | tig_arith ] ]
  end.

Definition find_in_array_timing_invs (a1 a2 : N)
    (t:trace) : option Prop :=
match t with (Addr a, s) :: t' => match a with
| 0x1e4 => Some (s R_A1 = a1 /\ s R_A2 = a2 /\ a1 < 2^32 /\ a2 < 2^32 /\ cycle_count_of_trace t' = 0)
| 0x1f8 => Some (tig_loop_inv (fun i => i < a2 /\
        s R_A1 = a1 /\
        s R_A2 = a2 /\
        s R_A5 = 0 ⊕ 1 * i /\
        a1 < 2^32 /\
        a2 < 2^32 /\
        cycle_count_of_trace t' = tfbeq + taddi + tjal + i * (tlw + taddi + ttbne + taddi + tfbeq)))
| 0x20c => Some (
        cycle_count_of_trace t = tfbeq + taddi + tjal + (msub 32 a2 1) * (tlw + taddi + ttbne + taddi + tfbeq) + tlw + taddi + ttbne + taddi + ttbeq + taddi + tjalr \/
        (exists j, j <= (msub 32 a2 1) /\ cycle_count_of_trace t = tfbeq + taddi + tjal + j * (tlw + taddi + ttbne + taddi + tfbeq) + tlw + taddi + tfbne + taddi + taddi + tjalr) \/
        cycle_count_of_trace t = ttbeq + taddi + tjalr)
| _ => None end | _ => None end.

Theorem find_in_array_timing:
  forall s t s' x' a1 a2
         (ENTRY: startof t (x',s') = (Addr entry_addr, s))
         (MDL: models rvtypctx s)
         (A1: s R_A1 = a1)
         (A2: s R_A2 = a2),
  satisfies_all
    lifted_prog
    (find_in_array_timing_invs a1 a2)
    exits
  ((x',s')::t).
Proof using.
    intros.
    pose proof (models_var R_A1 MDL) as B_A1; simpl in B_A1; rewrite A1 in B_A1.
    pose proof (models_var R_A2 MDL) as B_A2; simpl in B_A2; rewrite A2 in B_A2.
    apply prove_invs.
    Local Ltac step := tstep r5_step.
    (* TIG: variables that do not affect timing *)
    Ltac Picinae_riscv.ISA_RISCV.ignore_vars v ::= constr:(match v with
        R_A2 => true | _ => false end).

    simpl. rewrite ENTRY. unfold entry_addr. step.
    lazymatch goal with
    | |- tig_loop_inv _ => apply (tig_inv _ 0); cbv beta; tig_close 0 0
    | |- _ => tig_close 0 0
    end.

    intros.
    eapply startof_prefix in ENTRY; try eassumption.
    eapply preservation_exec_prog in MDL;
        try eassumption; [idtac|apply lift_riscv_welltyped].
    clear - ENTRY PRE MDL. rename t1 into t. rename s1 into s'.

    destruct_inv 32 PRE.

    (* 0x1e4: entry -> loop header / exit *)
    { destruct PRE as (A1 & A2 & B_A1 & B_A2 & Cycles).
      repeat step.
      all: lazymatch goal with
      | |- tig_loop_inv _ => apply (tig_inv _ 0); cbv beta; tig_close 0 0
      | |- context[ (Addr 0x20c, _) :: (Addr 0x208, _) :: _ ] => right; right; tig_close 0 0
      | |- ?g => idtac "TIG: unexpected goal:" g; fail "TIG: unexpected goal"
      end. }

    (* 0x1f8: loop header -> loop header / exit *)
    { destruct PRE as [i PRE]; cbv beta in PRE. destruct PRE as (L0 & L1 & L2 & L3 & B_A1 & B_A2 & Cycles).
      repeat step.
      all: lazymatch goal with
      | |- tig_loop_inv _ => apply (tig_inv _ (i + 1)); cbv beta; tig_close i i
      | |- context[ (Addr 0x20c, _) :: (Addr 0x208, _) :: _ ] => admit
      | |- ?g => idtac "TIG: unexpected goal:" g; fail "TIG: unexpected goal"
      end. }
Admitted.

