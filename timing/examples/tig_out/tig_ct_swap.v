Local Ltac tig_split_if c :=
  lazymatch c with true => fail | false => fail
  | negb ?c' => destruct c' eqn:? | _ => destruct c eqn:? end.
Local Ltac tig_ifs :=
  repeat (cbn [negb] in *; match goal with
    | |- context[if ?c then _ else _] => tig_split_if c
    | H: context[if ?c then _ else _] |- _ => tig_split_if c
    end); cbn [negb] in *.
(* turn mod and div into linear constraints *)
Local Ltac tig_pow :=
  repeat match goal with
  | |- context[2 ^ ?n] => let v := eval vm_compute in (2 ^ n) in change (2 ^ n) with v
  | H: context[2 ^ ?n] |- _ => let v := eval vm_compute in (2 ^ n) in change (2 ^ n) with v in H
  end.
Local Ltac tig_arith :=
  tig_bc; unfold msub in *;
  rewrite ?N.shiftl_mul_pow2, ?N.shiftr_div_pow2 in *; tig_pow;
  zify; Z.div_mod_to_equations; Z.quot_rem_to_equations; lia.
(* what psimpl leaves: x xor x (x86 xor eax, eax) and casts of 0 *)
Local Ltac tig_norm :=
  rewrite ?N.lxor_nilpotent, ?N.Div0.mod_0_l in *;
  repeat match goal with
  | |- context[scast ?a ?b 0] =>
      let v := eval vm_compute in (scast a b 0) in change (scast a b 0) with v
  end.
(* Split conjunctions and solve each one. On a path that leaves the loop, the
   iteration i equals the count n. *)
Local Ltac tig_close i n :=
  lazymatch goal with
  | |- _ /\ _ => split; [ tig_close i n | tig_close i n ]
  | |- _ => first [ assumption | reflexivity
                  | tig_norm;
                    (tryif constr_eq i n then idtac else replace i with n in * by tig_arith);
                    hammer; tig_ifs; solve [ lia | tig_arith ] ]
  end.

Definition ct_swap_timing_invs (a0 a2 a3 : N)
    (t:trace) : option Prop :=
match t with (Addr a, s) :: t' => match a with
| 0x1e4 => Some (s R_A0 = a0 /\ s R_A2 = a2 /\ s R_A3 = a3 /\ a0 < 2^32 /\ a2 < 2^32 /\ a3 < 2^32 /\ 4 * a3 < 2^32 /\ cycle_count_of_trace t' = 0)
| 0x1f0 => Some (tig_loop_inv (fun i => i <= a3 /\
        s R_A0 = (msub 32 0 a0) /\
        s R_A2 = a2 ⊕ 4 * i /\
        s R_A3 = ((a2 + ((N.shiftl a3 2) mod 2^32)) mod 2^32) /\
        a0 < 2^32 /\
        a2 < 2^32 /\
        a3 < 2^32 /\
        4 * a3 < 2^32 /\
        cycle_count_of_trace t' = tslli 2 + tsub + tadd + i * (ttbne + tlw + tlw + taddi + taddi + txor + tand + txor + tsw + tlw + txor + tsw + tjal)))
| 0x1f4 => Some (
        cycle_count_of_trace t = tslli 2 + tsub + tadd + a3 * (ttbne + tlw + tlw + taddi + taddi + txor + tand + txor + tsw + tlw + txor + tsw + tjal) + tfbne + tjalr)
| _ => None end | _ => None end.

Theorem ct_swap_timing:
  forall s t s' x' a0 a2 a3
         (ENTRY: startof t (x',s') = (Addr entry_addr, s))
         (MDL: models rvtypctx s)
         (A0: s R_A0 = a0)
         (A2: s R_A2 = a2)
         (A3: s R_A3 = a3)
         (ASSUME0: 4 * a3 < 2^32),
  satisfies_all
    lifted_prog
    (ct_swap_timing_invs a0 a2 a3)
    exits
  ((x',s')::t).
Proof using.
    intros.
    pose proof (models_var R_A0 MDL) as B_A0; simpl in B_A0; rewrite A0 in B_A0.
    pose proof (models_var R_A2 MDL) as B_A2; simpl in B_A2; rewrite A2 in B_A2.
    pose proof (models_var R_A3 MDL) as B_A3; simpl in B_A3; rewrite A3 in B_A3.
    apply prove_invs.
    Local Ltac step := tstep r5_step.
    (* TIG: variables that do not affect timing *)
    Ltac Picinae_riscv.ISA_RISCV.ignore_vars v ::= constr:(match v with
        R_A1 | R_A4 | R_A5 => true | _ => false end).

    simpl. rewrite ENTRY. unfold entry_addr. step.
    lazymatch goal with
    | |- tig_loop_inv _ => apply (tig_inv _ 0); cbv beta; tig_close 0 0
    | |- _ => tig_close 0 0
    end.

    intros.
    eapply startof_prefix in ENTRY; try eassumption.
    eapply preservation_exec_prog in MDL;
        try eassumption; [idtac|apply lift_riscv_welltyped].
    clear - ENTRY PRE MDL. rename t1 into t. rename s1 into s'.

    destruct_inv 32 PRE.

    (* 0x1e4: entry -> loop header / exit *)
    { destruct PRE as (A0 & A2 & A3 & B_A0 & B_A2 & B_A3 & ASSUME0 & Cycles).
      repeat step.
      all: lazymatch goal with
      | |- tig_loop_inv _ => apply (tig_inv _ 0); cbv beta; tig_close 0 0
      | |- ?g => idtac "TIG: unexpected goal:" g; fail "TIG: unexpected goal"
      end. }

    (* 0x1f0: loop header -> loop header / exit *)
    { destruct PRE as [i PRE]; cbv beta in PRE. destruct PRE as (L0 & L1 & L2 & L3 & B_A0 & B_A2 & B_A3 & ASSUME0 & Cycles).
      repeat step.
      all: lazymatch goal with
      | |- tig_loop_inv _ => apply (tig_inv _ (i + 1)); cbv beta; tig_close i i
      | |- context[ (Addr 0x1f4, _) :: (Addr 0x1f0, _) :: _ ] => tig_close i (a3)
      | |- ?g => idtac "TIG: unexpected goal:" g; fail "TIG: unexpected goal"
      end. }
Qed.

