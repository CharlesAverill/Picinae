Definition item_memory (s0:store) :=
  write_field32 (s0 V_MEM32) (s0 R_R0) item_container_offset 0.

Definition item_register_frame (s0 s:store) :=
  forall v, v <> V_MEM32 -> v <> R_R3 -> v <> F_N -> v <> F_Z ->
    s v = s0 v.

Definition item_post (s0 s:store) :=
  s V_MEM32 = item_memory s0 /\ s R_R3 = 0 /\
  s F_N = 0 /\ s F_Z = 1 /\ item_register_frame s0 s.

Definition item_exit (t:trace) :=
  match t with (Addr a,_)::_ => a =? 0x5a | _ => false end.

Definition item_invs (s0:store) (t:trace) : option Prop :=
  match t with (Addr a,s)::_ => match a with
  | 0x56 => Some (s = s0)
  | 0x5a => Some (item_post s0 s)
  | _ => None end | _ => None end.

Definition item_writable (s:store) :=
  forall i, i < 4 -> mem_writable s ((s R_R0 + 16 + i) mod 2^32).

Definition ordinary_item_lr (lr:N) := lr < 4294967280 /\ lr mod 2 = 1.

Definition item_entry (s:store) :=
  models armv6mtypctx s /\ object32 (s R_R0) list_item_size /\
  item_writable s /\ ordinary_item_lr (s R_LR).

